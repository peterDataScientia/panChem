import React, { useCallback, useEffect, useRef, useState } from 'react';
import { createRoot } from 'react-dom/client';
import { Editor } from 'ketcher-react';
import { StandaloneStructServiceProvider } from 'ketcher-standalone';
import 'ketcher-react/dist/index.css';
import { announceReady, onInput, saveResult } from './bridge';
import './style.css';

const provider = new StandaloneStructServiceProvider();

function KetcherBridge() {
  const editorRef = useRef(null);
  const inputRef = useRef({ molfile: '', smiles: '', molecule_key: '' });
  const loadedRef = useRef('');
  const [ready, setReady] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const [label, setLabel] = useState('');

  const loadInitial = useCallback(async () => {
    const editor = editorRef.current;
    const args = inputRef.current;
    if (!editor || !args.molecule_key || loadedRef.current === args.molecule_key) return;
    // Load a V2000 Molfile generated by RDKit. This preserves atom and
    // bond orders, coordinates, formal charges, stereochemistry when possible.
    const initial = args.molfile || args.smiles || '';
    if (initial) {
      try {
        await editor.setMolecule(initial);
      } catch (err) {
        setError('This structure could not be loaded. You can draw it manually.');
        return;
      }
    }
    loadedRef.current = args.molecule_key;
    setError('');
  }, []);

  useEffect(() => {
    const stop = onInput((args) => {
      inputRef.current = {
        molfile: String(args.molfile || ''),
        smiles: String(args.smiles || ''),
        molecule_key: String(args.molecule_key || ''),
      };
      setLabel(String(args.label || ''));
      loadInitial();
    });
    announceReady();
    return stop;
  }, [loadInitial]);

  const handleInit = useCallback((instance) => {
    editorRef.current = instance;
    setReady(true);
    loadInitial();
  }, [loadInitial]);

  const apply = async () => {
    if (!editorRef.current || busy) return;
    setBusy(true);
    setError('');
    try {
      const [smiles, molfile, sdf] = await Promise.all([
        editorRef.current.getSmiles(),
        editorRef.current.getMolfile('v2000'),
        editorRef.current.getSdf('v2000'),
      ]);
      if (!smiles?.trim() || !molfile?.trim()) {
        setError('Draw a chemical structure before applying your changes.');
        return;
      }
      saveResult({
        action: 'apply',
        smiles: smiles.trim(),
        molfile,
        sdf,
        molecule_key: inputRef.current.molecule_key,
      });
    } catch (err) {
      setError('Could not read this structure. Check its bonds and atom labels.');
      console.error('Ketcher export failed', err);
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="shell">
      <div className="topbar">
        <span className="heading">Draw or correct structure{label ? ': ' + label : ''}</span>
        <button className="apply" disabled={!ready || busy} onClick={apply}>
          {busy ? 'Saving…' : 'Apply structure'}
        </button>
      </div>
      <div className="editor">
        <Editor
          staticResourcesUrl="./"
          structServiceProvider={provider}
          disableMacromoleculesEditor={true}
          onInit={handleInit}
          errorHandler={() => setError('Could not complete an editor operation.')}
        />
      </div>
      <div className="foot">
        <span>{error || (!ready ? 'Opening structure editor…' : 'Edit atoms and bonds, then select Apply structure.')}</span>
      </div>
    </div>
  );
}

createRoot(document.getElementById('root')).render(<KetcherBridge />);
